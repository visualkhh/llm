# ============================================================================
# localization/slam_stub.py — 비주얼(카메라) 기반 로컬라이제이션 자리
#
# 라이다 기반 보정은 실제로 구현했다 (localization/lidar_localization_node.py).
# 카메라(뎁스+RGB) 기반 보정은 왜 아직 안 했는지:
#   - 라이다는 360도 전 방향을 보고 몸통에 고정돼 있어서 "지금 로봇이
#     지도의 어디쯤 있는지" 추정하기에 좋은 위치/시야를 가진다.
#   - 이 로봇의 카메라는 그리퍼(팔 끝)에 달려 있어서 팔이 움직이면
#     시야 자체가 계속 바뀐다 — "몸체가 움직인 양"과 "팔이 움직여서
#     생긴 카메라 시점 변화"를 분리해야 하는데(팔 관절 각도로 그 차이를
#     계산할 수는 있다), 게다가 시야각도 좁아서(87도) 라이다만큼
#     안정적인 로컬라이제이션 소스가 되기 어렵다.
#   - 그래도 실제 로봇에서는 카메라 기반 visual odometry(연속 프레임의
#     특징점 추적으로 자기 움직임을 추정)를 라이다와 함께 융합해서 쓰는
#     경우가 흔하다 — 여기 인터페이스만 남겨뒀다가, 원하면 다음 단계로
#     구현하면 된다 (특징점 추적 알고리즘 자체가 이 프로젝트의 다른
#     부분보다 난이도가 훨씬 높다).
# ============================================================================

from nodes.core import ComposableNode


class VisualOdometryNode(ComposableNode):
    """카메라 프레임 사이의 특징점 이동으로 자체 움직임을 추정하는 게
    목표인 노드 — 아직 미구현 (위 설명 참고).

    TODO(다음 단계): 연속된 두 프레임의 depth+RGB로 카메라(=그리퍼) 움직임을
    추정(visual odometry). 팔이 움직일 때도 카메라가 같이 움직이므로,
    "팔 관절 각도로 이미 알고 있는 카메라 움직임"을 빼줘야 순수하게
    "몸체가 움직인 만큼"만 남길 수 있다는 점이 포인트.
    """

    def __init__(self, bus, rate_hz=5.0):
        super().__init__("slam_visual", bus)
        self.create_timer(rate_hz, self._tick)

    def _tick(self):
        pass  # TODO: visual feature tracking
